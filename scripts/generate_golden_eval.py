def generate_golden_dataset():
    out_path = Path("data/golden/golden_eval.csv")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    # Assign alternating 50/50 split (100 calibration, 100 locked_test)
    fieldnames = [
        "example_id",
        "tweet_id",
        "text",
        "intent_label",
        "escalation_label",
        "escalation_reason",
        "risk_tags",
        "context_needed",
        "split",
        "annotator_notes",
    ]

    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for i, row in enumerate(EXAMPLES):
            split = "calibration" if (i % 2 == 0) else "locked_test"
            writer.writerow(
                {
                    "example_id": row[0],
                    "tweet_id": row[1],
                    "text": row[2],
                    "intent_label": row[3],
                    "escalation_label": row[4],
                    "escalation_reason": row[5],
                    "risk_tags": row[6],
                    "context_needed": row[7],
                    "split": split,
                    "annotator_notes": row[8],
                }
            )

    print(f"Generated {len(EXAMPLES)} golden evaluation examples at {out_path}")
    manifest = freeze_golden_evaluation(out_path)
    print(f"Frozen at {manifest}")


if __name__ == "__main__":
    generate_golden_dataset()
